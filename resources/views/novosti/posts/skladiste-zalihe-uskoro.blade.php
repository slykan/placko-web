<p>
    Puno korisnika plačko.app-a ne prodaje samo usluge, nego i fizičku robu — pa se prije ili
    kasnije postavi isto pitanje: <strong>koliko toga još imam na skladištu?</strong> Modul
    <strong>Skladište</strong>, koji smo najavili u srpnju, sada je dostupan i nadovezuje se na
    postojeći katalog proizvoda te na izradu ponuda i računa.
</p>

<div class="callout">
    Skladište nalaziš u izborniku aplikacije. Zaliha se vodi za artikle iz kataloga na kojima je
    uključeno „Prati zalihu" — usluge (rad, savjetovanje) nemaju zalihu i na njih se modul ne odnosi.
</div>

<h2>Što skladište radi</h2>
<ul>
    <li><strong>Zaliha po proizvodu i skladištu</strong> — svaki proizvod ima trenutnu količinu, a ako posluješ na više lokacija, možeš otvoriti više skladišta i jedno označiti kao zadano.</li>
    <li><strong>Primke</strong> — kad nabaviš robu, uneseš primku s dobavljačem, skladištem, količinama i nabavnim cijenama. Primka povećava zalihu, a nabavna cijena računa se kao <strong>prosječna ponderirana</strong> cijena svih nabava.</li>
    <li><strong>Automatsko smanjenje zalihe</strong> — kad izdaš račun sa stavkom proizvoda, prodana količina oduzima se sa skladišta. Ponuda sama ne mijenja zalihu, tek račun.</li>
    <li><strong>Dobavljači</strong> — vlastiti popis dobavljača, povezan s primkama.</li>
    <li><strong>Upozorenje na nisku zalihu</strong> — po proizvodu postaviš minimalnu količinu, a na nadzornoj ploči vidiš što treba naručiti.</li>
    <li><strong>Vrijednost zalihe</strong> — uz svaku stavku vidiš vrijednost robe na skladištu prema nabavnoj cijeni.</li>
    <li><strong>Inventura</strong> — upišeš stvarno stanje, aplikacija pokaže očekivanu količinu i razliku (manjak ili višak) te nakon potvrde ispravi zalihu.</li>
</ul>

<h2>Kako krenuti, u tri koraka</h2>
<ol>
    <li>U katalogu na artiklima koje prodaješ uključi <strong>„Prati zalihu"</strong> i, po želji, upiši minimalnu zalihu.</li>
    <li>Unesi početno stanje — najjednostavnije prvom primkom ili inventurom.</li>
    <li>Nastavi izdavati račune kao i do sada — zaliha se dalje vodi sama.</li>
</ol>

<h2>Skladište i paušalni obrt</h2>
<p>
    Paušalisti ne vode zalihe za porezne potrebe — porez se plaća prema naplaćenim primicima iz knjige
    prometa, neovisno o tome koliko robe imaš na skladištu. Skladište u plačko.app-u zato služi prvenstveno
    tebi: da znaš što imaš, što se prodaje i kada naručiti, bez Excela. Ako vodiš obrt na dohodak ili
    tvrtku, evidencija zaliha korisna je i kao podloga knjigovođi.
</p>

<p>
    Cilj je bio da, kao i kod ponuda i računa, sve ostane jednostavno — bez knjigovodstvenog žargona i
    bez nepotrebnih koraka. Ako prodaješ robu i nešto ti nedostaje, javi nam se s prijedlogom — utječe na
    redoslijed kojim gradimo dalje.
</p>
