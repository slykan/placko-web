<p>
    Ponuda je tek pola posla. Druga polovica je ono što se događa nakon slanja: je li je klijent pročitao,
    je li pristao, i kad pristane — koliko ti treba da od nje napraviš račun. U plačko.app taj je put
    sad gotovo potpuno automatiziran.
</p>

<h2>1. Klijent prihvaća ponudu izravno iz maila</h2>
<p>
    Kad ponudu pošalješ gumbom <strong>Pošalji</strong>, klijent dobiva uredan mail s PDF-om ponude u
    privitku i velikim gumbom <strong>✓ Prihvati ponudu</strong>. Jedan klik i gotovo — klijent ne treba
    ništa ispisivati, potpisivati ni skenirati, niti se prijavljivati bilo gdje.
</p>
<ul>
    <li>Link u mailu je <strong>potpisan</strong> — vrijedi samo za tu ponudu i ne može se krivotvoriti ni „pogoditi".</li>
    <li>Klijent nakon klika vidi stranicu s potvrdom da je ponuda prihvaćena.</li>
    <li>Ako slučajno klikne dvaput, ništa se ne mijenja — bilježi se prvo prihvaćanje.</li>
</ul>

<h2>2. Ti odmah dobiješ obavijest</h2>
<p>
    U trenutku prihvaćanja na mail tvrtke stiže poruka <em>„Ponuda 3-1-2026 je prihvaćena"</em>. U popisu
    ponuda stupac <strong>Prihvaćena</strong> pokazuje zelenu kvačicu, a sivi sat za ponude koje još
    čekaju odgovor. Kad mišem prijeđeš preko kvačice, vidiš točan datum i vrijeme prihvaćanja.
</p>
<div class="callout">
    Savjet: filtriraj popis ponuda po godini i odmah vidiš koje su ponude prihvaćene, a koje bi trebalo
    „podsjetiti" — korisno pred kraj mjeseca kad planiraš posao.
</div>

<h2>3. Od prihvaćene ponude do računa — jedan klik</h2>
<p>
    U odjeljku <strong>Računi</strong> klikni <strong>Račun iz ponude</strong> i odaberi ponudu. Aplikacija
    u novi račun automatski prepiše:
</p>
<ul>
    <li>klijenta,</li>
    <li>sve stavke — usluge i proizvode, količine, cijene, rabate i PDV stope,</li>
    <li>napomenu i mjesto izdavanja.</li>
</ul>
<p>
    Račun dobiva sljedeći broj u numeraciji i spreman je za provjeru, PDF s HUB-3 barkodom i slanje
    mailom. Nema ponovnog tipkanja i nema rizika da cijena na računu ne odgovara onoj koju je klijent
    prihvatio u ponudi.
</p>

<h2>Cijeli tijek u 30 sekundi</h2>
<ol>
    <li>Izradi ponudu i klikni <strong>Pošalji</strong>.</li>
    <li>Klijent u mailu klikne <strong>Prihvati ponudu</strong>.</li>
    <li>Ti dobiješ obavijest, a ponuda u popisu dobije zelenu kvačicu.</li>
    <li>U Računima klikneš <strong>Račun iz ponude</strong>, provjeriš i izdaš račun.</li>
</ol>
