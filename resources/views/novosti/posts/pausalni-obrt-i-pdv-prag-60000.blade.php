<p>
    „Moram li ući u PDV?" jedno je od prvih pitanja svakog paušalista koji raste. Od 2025. godine
    pravila su jednostavnija: i granica za paušal i prag za ulazak u sustav PDV-a iznose
    <strong>60.000 €</strong>. Ovaj vodič objašnjava što to znači, kada točno ulaziš u PDV i na što
    paziti kod rada sa stranim klijentima.
</p>

<h2>Prag od 60.000 €</h2>
<p>
    Izmjenama Zakona o PDV-u (NN 152/24) prag za obvezan ulazak u sustav PDV-a povećan je s 40.000 € na
    <strong>60.000 €</strong> godišnjeg prometa, a primjenjuje se od <strong>1. siječnja 2025.</strong>
    Prag se odnosi na vrijednost isporuka u tuzemstvu bez PDV-a u prethodnoj ili tekućoj kalendarskoj
    godini.
</p>
<p>
    Paušalni obrt i PDV se međusobno isključuju: paušalist ne smije biti u sustavu PDV-a. Dok si ispod
    praga, na računima <strong>ne iskazuješ PDV</strong>, nego navodiš napomenu da obveznik nije u
    sustavu PDV-a, uz poziv na članak 90. Zakona o PDV-u.
</p>

<h2>Što ako prijeđeš prag tijekom godine?</h2>
<p>
    Od 2025. upis u registar obveznika PDV-a ne čeka početak sljedećeg mjeseca: obveza nastaje od
    <strong>prvog dana nakon što je prag prijeđen</strong>. U praksi to znači:
</p>
<ul>
    <li>prati zbroj primitaka tijekom godine — ako se približavaš 60.000 €, razgovaraj s knjigovođom <em>prije</em> nego što prag prijeđeš,</li>
    <li>od dana nakon prelaska praga račune izdaješ s PDV-om i vodiš evidencije kao obveznik PDV-a,</li>
    <li>istodobno prestaješ ispunjavati uvjete za paušalno oporezivanje, pa obrt prelazi na oporezivanje dohotka (vođenje knjige primitaka i izdataka).</li>
</ul>
<div class="callout">
    Paušalist koji zna da će uskoro prijeći prag može se i <strong>dobrovoljno</strong> upisati u sustav
    PDV-a, ali tada gubi pravo na paušal. To ima smisla ako su ti klijenti uglavnom tvrtke u sustavu
    PDV-a (one PDV ionako odbijaju kao pretporez) — za klijente građane PDV znači 25 % veću cijenu.
</div>

<h2>Strani klijenti i PDV identifikacijski broj</h2>
<p>
    Ako kao paušalist pružaš <strong>usluge poreznim obveznicima iz drugih država EU</strong> (npr.
    programiranje ili dizajn za tvrtku iz Njemačke), vrijedi pravilo prijenosa porezne obveze: PDV
    obračunava kupac u svojoj državi. Za takve usluge paušalist i ispod praga treba
    <strong>PDV identifikacijski broj</strong> (HR + OIB) i mora predavati zbirne prijave (obrazac ZP).
    Nabava usluga od stranih tvrtki (npr. oglašavanje, softver) također može zahtijevati PDV
    identifikacijski broj i obračun PDV-a u Hrvatskoj.
</p>
<p>
    Za klijente <strong>izvan EU</strong> pravila su drukčija. Budući da su ove situacije česte i
    lako je pogriješiti, prije prvog računa stranom klijentu provjeri točnu napomenu na računu i obveze
    prijave s knjigovođom ili u Poreznoj upravi.
</p>

<h2>Kontrolna lista</h2>
<ol>
    <li>Na svakom računu napomena da nisi u sustavu PDV-a (čl. 90. Zakona o PDV-u).</li>
    <li>Mjesečno prati zbroj naplaćenih primitaka — ili neka to radi program.</li>
    <li>Kod 50.000 € i više razgovaraj s knjigovođom o prijelazu.</li>
    <li>Prije rada s klijentima iz EU provjeri treba li ti PDV identifikacijski broj.</li>
</ol>

<div class="warn">
    Ovo je opći pregled, ne porezni savjet. Pravila PDV-a kod prekograničnih usluga složena su i
    ovise o konkretnoj situaciji — provjeri s knjigovođom ili u Poreznoj upravi.
</div>

