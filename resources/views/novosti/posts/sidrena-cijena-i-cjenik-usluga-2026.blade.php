<p>
    Od <strong>1. listopada 2026.</strong> obveza isticanja <strong>dodatne, tzv. sidrene cijene</strong> više
    se ne odnosi samo na hranu i drogeriju u trgovinama. Prema odlukama Vlade objavljenima u
    <strong>Narodnim novinama br. 101/2026</strong>, obuhvaćeni su <strong>svi proizvodi i — prvi put — sve usluge</strong>.
    To znači da se tiče i frizera, servisera, majstora, IT obrtnika, fotografa, kozmetičara i većine
    ostalih paušalista koji naplaćuju usluge građanima.
</p>

<h2>Što je sidrena cijena?</h2>
<p>
    Sidrena (dodatna) cijena je cijena proizvoda ili usluge na <strong>određeni referentni dan</strong>, koja
    se ističe <strong>uz trenutnu cijenu</strong> kako bi kupac vidio je li cijena u međuvremenu porasla.
</p>
<div class="table-wrap">
<table>
    <tr><th>Što prodaješ</th><th>Sidrena cijena je cijena na dan</th></tr>
    <tr><td>Hrana, piće, kozmetika, sredstva za čišćenje, toaletne potrepštine i proizvodi za kućanstvo (već obuhvaćeno ranije)</td><td class="num">2. svibnja 2025.</td></tr>
    <tr><td>Svi ostali proizvodi i sve usluge (novo)</td><td class="num">10. rujna 2026.</td></tr>
</table>
</div>
<p>
    <strong>Primjer:</strong> ako je usluga 10. rujna 2026. koštala 40 €, a danas je 45 €, na cjeniku uz
    45 € mora pisati i sidrena cijena od 40 €. Ako cijenu nisi mijenjao, obje su cijene iste — ali obje
    moraju biti istaknute.
</p>

<h2>Gdje se mora istaknuti</h2>
<ul>
    <li>Na prodajnom ili uslužnom mjestu, <strong>na istom mjestu gdje je i trenutna cijena</strong> — ako imaš cjenik usluga na zidu, sidrena cijena ide u isti cjenik.</li>
    <li>U web trgovini i na web stranici, uz cijenu proizvoda ili usluge.</li>
    <li>U oglašavanju — letci, plakati, oglasi na mreži i digitalni oglasi s cijenom.</li>
</ul>
<p>Cijene moraju biti istaknute jasno, vidljivo i čitljivo.</p>

<h2>Nova obveza: strojno čitljiv cjenik na webu</h2>
<p>
    Druga odluka iz istog paketa traži da trgovci i pružatelji usluga <strong>koji imaju web stranicu</strong>
    na njoj objavljuju cjenik u strojno čitljivom obliku — <strong>CSV ili XML</strong> datoteci. Za pružatelje
    usluga cjenik mora sadržavati barem:
</p>
<ul>
    <li>naziv usluge,</li>
    <li>maloprodajnu cijenu,</li>
    <li>oznaku je li cijena akcijska,</li>
    <li>sidrenu cijenu.</li>
</ul>
<p>
    Pružatelji usluga cjenik ažuriraju nakon svake promjene cijene (do 8 sati ujutro), a trgovci robom
    svakodnevno. Objavljeni cjenici čuvaju se najmanje 30 dana.
</p>

<div class="warn">
    <strong>Kazne su ozbiljne:</strong> za obrtnike i samostalne djelatnike propisane su novčane kazne od
    1.000 do 20.000 eura, a nadzor se već provodi. Ako nisi siguran kako se pravila odnose na tvoju
    djelatnost, provjeri s knjigovođom ili obrtničkom komorom.
</div>

<h2>Kako to izgleda u praksi — naš primjer</h2>
<p>
    I plačko.app je pružatelj usluge, pa smo pravila primijenili na vlastiti cjenik:
</p>
<ul>
    <li>na <a href="/#cijene" style="color:var(--p);font-weight:700;">stranici s cijenama</a> uz svaki paket piše i <strong>sidrena cijena</strong>,</li>
    <li>cjenik je dostupan i kao CSV datoteka na stalnoj adresi <a href="/cjenik.csv" style="color:var(--p);font-weight:700;">placko.app/cjenik.csv</a>, s nazivom, cijenom, jedinicom i sidrenom cijenom,</li>
    <li>prikazana cijena i sidrena cijena dolaze iz istog izvora, pa ne mogu „pobjeći" jedna od druge kad se cjenik promijeni.</li>
</ul>
<p>
    Za mali obrt s desetak usluga najjednostavnije je isto: tablica s četiri stupca (naziv, cijena,
    akcija da/ne, sidrena cijena), spremljena kao CSV i objavljena na stalnoj adresi na tvojoj web
    stranici, te poveznica na nju uz cjenik.
</p>

<h2>Kontrolna lista za pružatelje usluga</h2>
<ol>
    <li>Zapiši cijene svih usluga kakve su bile <strong>10. rujna 2026.</strong> — to su tvoje sidrene cijene.</li>
    <li>Dopuni cjenik u poslovnom prostoru: uz svaku cijenu i sidrenu cijenu.</li>
    <li>Isto napravi na web stranici, društvenim mrežama i u oglasima gdje navodiš cijene.</li>
    <li>Ako imaš web stranicu, objavi cjenik kao CSV ili XML i ažuriraj ga nakon svake promjene cijene.</li>
    <li>Čuvaj stare verzije cjenika najmanje 30 dana.</li>
</ol>

