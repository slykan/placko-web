<p>
    Paušalni obrt je najjednostavniji oblik samostalne djelatnosti u Hrvatskoj: porez se ne računa iz
    stvarne dobiti nego iz <strong>razreda</strong> u koji upadaš prema ukupnim primicima, a doprinosi su
    fiksni. U ovom vodiču na jednom mjestu su svi iznosi i rokovi za <strong>2026. godinu</strong>.
</p>

<h2>1. Porezni razredi u 2026.</h2>
<p>
    Razred se određuje prema ukupnim <strong>primicima</strong> (svemu što je naplaćeno u godini, ne prema
    dobiti). Svakom razredu pripada fiksni godišnji paušalni dohodak, a porez je <strong>12 %</strong> tog dohotka.
    Gornja granica za paušalno oporezivanje je <strong>60.000 €</strong> primitaka godišnje.
</p>
