<h3>PO-SD obrazac</h3>
<p>
    PO-SD je godišnje izvješće o paušalnom dohotku: iskazuješ ukupne primitke za prethodnu godinu, a iz
    njih se određuje razred i porez za tekuću godinu. Predaje se putem ePorezne do 15. siječnja. U
    plačko.app PO-SD se automatski izračunava iz izdanih računa, kao i knjiga izlaznih računa po godinama.
</p>

<h3>PDV prag</h3>
<p>
    Kad primici u godini prijeđu <strong>60.000 €</strong>, obrtnik izlazi iz paušalnog oporezivanja i ulazi
    u sustav PDV-a. Prati promet tijekom godine — ne čekaj prosinac.
</p>

<h2>5. Što se najavljuje za 2027.</h2>
<div class="warn">
    Vlada je u srpnju 2026. predstavila izmjene poreznih propisa koje bi se primjenjivale od
    <strong>1. siječnja 2027.</strong> Prema prijedlogu, za paušaliste s primicima do 40.000 € sve ostaje
    isto, a u 6. i 7. razredu porez i doprinosi rastu (godišnje otprilike +1.336 € u 6. i +3.033 € u 7.
    razredu). Izmjene su u zakonodavnoj proceduri — iznose za 2027. objavit ćemo kad budu konačni.
</div>

