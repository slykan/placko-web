<p>
    Paušalist ne vodi dvojno knjigovodstvo ni knjigu primitaka i izdataka — ali jednu evidenciju mora
    voditi uredno: <strong>knjigu prometa</strong>, poznatu i kao <strong>KPR</strong>. Iz nje na
    kraju godine ispunjavaš PO-SD obrazac, a na temelju nje se određuje i tvoj porezni razred. Evo što
    je to, što se upisuje i najčešće pogreške.
</p>

<h2>Što je knjiga prometa</h2>
<p>
    Knjiga prometa je kronološki popis svih <strong>naplaćenih</strong> primitaka obrta. Za paušalista
    je ključno upravo to: upisuje se novac koji je stvarno <em>naplaćen</em>, a ne račun u trenutku
    kad je izdan. Račun izdan u prosincu, a plaćen u siječnju, ulazi u primitke sljedeće godine.
</p>

<h2>Što se upisuje</h2>
<p>Za svaki naplaćeni račun u KPR se bilježi:</p>
<ul>
    <li><strong>redni broj</strong> upisa,</li>
    <li><strong>datum</strong> naplate,</li>
    <li><strong>broj i datum računa</strong> na koji se naplata odnosi,</li>
    <li><strong>iznos naplaćen u gotovini</strong> (u smislu fiskalizacije to uključuje i kartice),</li>
    <li><strong>iznos naplaćen bezgotovinski</strong> (uplata na transakcijski račun),</li>
    <li><strong>ukupno</strong> — zbroj gotovinskih i bezgotovinskih primitaka.</li>
</ul>
<p>
    Na kraju godine zbroj stupca „ukupno" daje tvoje godišnje primitke, koje prenosiš u PO-SD obrazac.
    Primitkom se smatraju i <strong>predujmovi</strong> — novac koji ti klijent uplati unaprijed ulazi
    u KPR na dan uplate.
</p>

<h2>Koliko često upisivati</h2>
<p>
    Upis se radi <strong>na dan naplate</strong>, odnosno najkasnije kad saznaš za uplatu (npr. iz
    izvoda banke). Najlakše je jednom tjedno proći izvod i upisati sve uplate, a gotovinske naplate
    upisivati odmah, kad izdaš račun.
</p>

<h2>Papir, Excel ili aplikacija?</h2>
<p>
    Zakon ne propisuje alat — KPR možeš voditi na papirnatom obrascu, u tablici ili u programu za
    račune. Bitno je da je uredna, kronološka i da se može ispisati na zahtjev porezne inspekcije.
    Programi poput plačko.app vode je automatski: kad račun označiš kao plaćen (ili ga naplatiš na
    licu mjesta), upis u KPR nastaje sam, a godišnji zbroj je spreman za PO-SD.
</p>

<h2>Najčešće pogreške</h2>
<ul>
    <li><strong>Upis izdanih umjesto naplaćenih računa</strong> — vodi do pogrešnog zbroja i, u najgorem slučaju, do višeg poreznog razreda nego što treba.</li>
    <li><strong>Zaboravljeni predujmovi</strong> — uplata unaprijed je primitak onog dana kad je stigla.</li>
    <li><strong>Djelomična plaćanja</strong> — ako klijent plati u dva dijela, upisuju se dva upisa, svaki na dan uplate.</li>
    <li><strong>Povrati</strong> — ako klijentu vratiš novac, to se evidentira kao umanjenje primitka (storno), uz odgovarajući dokument.</li>
    <li><strong>Nevođenje uopće</strong> — za neuredno vođenje evidencija predviđene su novčane kazne, a KPR je prvo što inspektor traži.</li>
</ul>

<h2>Koliko je čuvati</h2>
<p>
    Knjigu prometa i račune čuvaj najmanje do isteka roka zastare prava na utvrđivanje poreza — praksa
    je čuvati ih <strong>najmanje 11 godina</strong>, isto kao i ostalu poslovnu dokumentaciju. Ako je
    vodiš elektronički, napravi i rezervnu kopiju.
</p>

