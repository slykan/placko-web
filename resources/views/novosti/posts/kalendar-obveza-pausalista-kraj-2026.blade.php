<h2>17. studenoga: bazna cijena</h2>
<p>
    Obveza isticanja sidrene cijene odgođena je s 1. listopada na 17. studenoga 2026., a od tog dana
    Zakon o zaštiti potrošača istu cijenu naziva <strong>bazna cijena</strong>. Uz cijenu proizvoda ili
    usluge ističe se i cijena s referentnog dana (za usluge i većinu proizvoda 10. rujna 2026.), a tko ima
    web stranicu objavljuje i važeći cjenik. Pravilnici koji razrađuju detalje bili su do početka studenoga
    još u obliku nacrta. Sve pojedinosti i službeni dokumenti:
    <a href="{{ route('novosti.show', 'bazna-cijena-od-17-studenoga-2026') }}" style="color:var(--p);font-weight:700;">Bazna cijena od 17. studenoga 2026.</a>
</p>

<h2>Prosinac: zatvori godinu</h2>
<ul>
    <li><strong>Naplati otvorene račune</strong> prije 31. prosinca ako možeš — paušalist plaća porez prema naplaćenim primicima, pa račun naplaćen 2. siječnja ulazi u primitke 2027.</li>
    <li><strong>Provjeri knjigu prometa</strong>: je li upisana svaka uplata, i gotovinska i na račun. Iz nje se ispunjava PO-SD.</li>
    <li><strong>Pogledaj ukupne primitke</strong>: ako si prešao granicu razreda, porez za 2027. određuje se prema novom razredu; ako se bližiš 60.000 €, razmisli o PDV-u na vrijeme (<a href="{{ route('novosti.show', 'pausalni-obrt-i-pdv-prag-60000') }}" style="color:var(--p);font-weight:700;">vodič o PDV pragu</a>).</li>
    <li><strong>Pripremi se za eRačun</strong>: OIB i adresa za sve klijente, građani označeni kao fizičke osobe, probni eRačun prije Nove godine (<a href="{{ route('novosti.show', 'eracun-od-2027-kako-ga-izdati-pausalist') }}" style="color:var(--p);font-weight:700;">kako izdati eRačun</a>).</li>
</ul>

<h2>Što se (možda) mijenja u 2027.</h2>
<div class="warn">
    Vlada je u rujnu 2026. uputila Saboru paket poreznih izmjena koji bi se primjenjivao od
    <strong>1. siječnja 2027.</strong> Prema prijedlogu, paušalisti s primicima do 40.000 € plaćaju isto
    kao i dosad, a paušalni dohodak raste u 6. razredu sa 7.500 € na 15.000 €, a u 7. razredu s 9.000 € na
    27.000 €. Do 3. studenoga 2026. nismo našli objavu konačnog teksta u Narodnim novinama — zato iznose
    za 2027. još ne upisujemo u kalkulatore. Ažurirat ćemo ih čim izmjene budu objavljene.
</div>
<p>
    Osnovica za doprinose mijenja se svake godine i objavljuje se naredbom krajem prosinca. Doprinosi za
    siječanj 2027. (plaćaju se do 15. veljače) obračunavaju se već po novoj osnovici.
</p>

<h2>15. siječnja 2027.: PO-SD</h2>
<p>
    PO-SD za 2026. predaje se putem ePorezne do 15. siječnja 2027. U obrascu se iskazuju ukupni primici
    iz knjige prometa, a iz njih se određuje razred i porez za 2027. Korak po korak:
    <a href="{{ route('novosti.show', 'po-sd-obrazac-pausalni-obrt') }}" style="color:var(--p);font-weight:700;">PO-SD obrazac — kako i do kada</a>.
    U plačko.app PO-SD je izračunat automatski iz naplaćenih računa (izbornik <strong>Obrasci</strong>, gdje ga preuzmeš kao PDF).
</p>

