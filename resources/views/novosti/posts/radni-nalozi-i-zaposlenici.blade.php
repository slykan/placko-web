<p>
    Kad posao radi više ljudi, papirnati radni nalog brzo postane usko grlo: treba ga ispisati, predati,
    pričekati da se vrati popunjen i onda sve prepisati u račun. U plačko.app sad postoje
    <strong>radni nalozi i zaposlenici</strong> — nalog stiže zaposleniku na mobitel, on na terenu upiše
    što je napravio, klijent se potpiše prstom, a ti iz naloga jednim klikom radiš račun.
</p>

<h2>1. Dodaj zaposlenike</h2>
<p>
    U izborniku <strong>Zaposlenici</strong> (odmah ispod naziva tvrtke) upišeš ime i prezime, radno mjesto,
    e-mail i <strong>cijenu sata rada</strong>. Zaposlenik se ne prijavljuje u plačko.app i ne treba mu
    lozinka — svaki dobiva svoj osobni link na kojem vidi samo svoje naloge.
</p>
<ul>
    <li>Bivše zaposlenike samo isključiš (<em>Aktivan</em>) — ostaju zapisani na starim nalozima.</li>
    <li>U popisu vidiš koliko tko ima otvorenih naloga i koliko je sati odradio ovaj mjesec.</li>
    <li><strong>Izvoz sati (CSV)</strong> daje sve upisane sate za odabrani mjesec po zaposleniku, sa zbrojem — korisno za plaće i obračun učinka.</li>
</ul>

<h2>2. Otvori radni nalog</h2>
<p>
    U <strong>Radnim nalozima</strong> klikni <strong>+ Novi radni nalog</strong>. Upisuješ klijenta,
    <strong>predmet</strong> (uređaj, vozilo, objekt…), lokaciju, rok i opis posla, a zatim odabereš
    nositelja posla i ostale izvršitelje. Materijal i usluge dodaješ iz svog cjenika, kao na ponudi.
</p>
<div class="callout">
    Klijent je prihvatio ponudu? Klikni <strong>Nalog iz ponude</strong> — klijent i sve stavke ponude
    prepišu se na nalog, pa samo dodaš izvršitelje.
</div>

<h2>3. Pošalji nalog zaposleniku</h2>
<p>
    Gumb s omotnicom <strong>Pošalji zaposleniku</strong> šalje svakom izvršitelju njegov mail s velikim
    gumbom <strong>✓ Prihvati i otvori nalog</strong>. Kad ga prihvati, u popisu naloga uz njegovo ime
    pojavi se zelena kvačica, a nalog prelazi u status <em>U tijeku</em>. Ako netko radije koristi
    WhatsApp, u istom prozoru kopiraš njegov osobni link i pošalješ ga porukom.
</p>

<h2>4. Zaposlenik sve upisuje na mobitelu</h2>
<p>
    Na stranici <strong>Moji nalozi</strong> zaposlenik vidi otvorene i zatvorene naloge. Telefon klijenta
    je jedan dodir do poziva, a adresa se otvara u Google Mapsu. U nalogu upisuje:
</p>
<ul>
    <li><strong>datum i vrijeme dolaska</strong> i koliko je sati radio (kalendar na hrvatskom, 24 h),</li>
    <li><strong>materijal</strong> — nazivi se nude iz tvog cjenika, a cijene ne vidi,</li>
    <li><strong>izvršene radove</strong>,</li>
    <li><strong>potpis klijenta</strong> — klijent se potpiše prstom na ekranu i upiše ime.</li>
</ul>
<p>
    Kad označi <strong>Posao je završen</strong>, tebi stiže mail s brojem sati i opisom radova. Nalog može
    dopunjavati sve dok ne izdaš račun; nakon toga je zaključan.
</p>

<h2>5. Račun iz naloga — jednim klikom</h2>
<p>
    Na završenom nalogu klikni <strong>Izradi račun</strong>. Sati se zbrajaju po cijeni sata u stavke
    <em>Rad</em>, materijal se prepiše sa svim cijenama i PDV-om, a ako vodiš skladište, zaliha se skine
    automatski. Račun se otvara za provjeru, a nalog dobiva status <em>Naplaćen</em>.
</p>
<p>
    Ako ti ipak treba papir, nalog ima dva PDF-a: <strong>za zaposlenika</strong> (bez cijena, s mjestom
    za upis sati i potpis) i <strong>za klijenta</strong> (s iznosima i potpisom klijenta).
</p>

<h2>Cijeli tijek ukratko</h2>
<ol>
    <li>Otvori nalog (ili ga napravi iz prihvaćene ponude) i dodaj izvršitelje.</li>
    <li>Klikni <strong>Pošalji zaposleniku</strong> — on nalog prihvati iz maila.</li>
    <li>Na terenu upiše dolazak, sate, materijal i radove, a klijent se potpiše na ekranu.</li>
    <li>Označi <strong>Posao je završen</strong> — ti dobiješ obavijest.</li>
    <li>Klikneš <strong>Izradi račun</strong>, provjeriš i izdaš.</li>
</ol>

<h2>Česta pitanja</h2>
<h3>U kojem su paketu radni nalozi?</h3>
<p>
    Radni nalozi i zaposlenici dio su paketa <strong>Pro</strong> i <strong>Business</strong>. Starter i
    dalje ima sve za račune, ponude, fiskalizaciju i skladište jedne tvrtke ili obrta. Usporedbu paketa
    pogledaj na <a href="{{ url('/#cijene') }}" style="color:var(--p);font-weight:700;">cjeniku</a>.
</p>
<h3>Treba li zaposleniku lozinka ili aplikacija?</h3>
<p>
    Ne. Dovoljan je mobitel s preglednikom. Osobni link otvara samo njegove naloge — tuđe naloge i sate
    kolega ne može mijenjati, a cijene i podaci tvrtke mu nisu vidljivi.
</p>
<h3>Što ako link dođe u krive ruke?</h3>
<p>
    Na kartici zaposlenika klikni <strong>Novi link</strong>. Stari link i svi linkovi iz već poslanih
    mailova odmah prestaju raditi, a novi pošalješ zaposleniku.
</p>
<h3>Mogu li sam upisivati sate umjesto zaposlenika?</h3>
<p>
    Možeš. U nalogu u uredu imaš istu evidenciju rada (datum i vrijeme dolaska, zaposlenik, sati, cijena
    sata), pa nalog možeš voditi i potpuno sam, bez slanja zaposlenicima.
</p>
