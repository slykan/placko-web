<p>
    Ponuda, predračun i račun izgledaju slično — svi imaju stavke, cijene i ukupni iznos — ali imaju
    sasvim različitu ulogu, i pravnu i poreznu. Zamjena jednog drugim česta je pogreška malih
    poduzetnika. Evo kada koristiti koji dokument.
</p>

<h2>Ponuda</h2>
<p>
    Ponuda je <strong>prijedlog</strong> po kojem bi se posao obavio: što, koliko, po kojoj cijeni i do
    kada. Ona još ne stvara obvezu plaćanja. Kad je klijent prihvati, nastaje dogovor (ugovor) — ponuda
    je tada dokaz o onome što je ugovoreno.
</p>
<ul>
    <li>Navedi <strong>rok valjanosti</strong> (npr. 15 ili 30 dana), da cijena ne vrijedi zauvijek.</li>
    <li>Opiši posao dovoljno precizno da se kasnije zna što je uključeno, a što je dodatni rad.</li>
    <li>Ponuda se <strong>ne upisuje</strong> u knjigu prometa i ne fiskalizira se.</li>
    <li>Najbolje je tražiti pisanu potvrdu prihvata — e-mail ili klik na „Prihvati ponudu".</li>
</ul>

<h2>Predračun</h2>
<p>
    Predračun je <strong>poziv na plaćanje unaprijed</strong> — klijentu kažeš koliko i kamo treba
    platiti prije nego što posao napraviš ili robu isporučiš. Predračun <strong>nije račun</strong>: ne
    mora imati sve elemente računa, ne fiskalizira se i ne ulazi u knjigu prometa dok novac ne stigne.
</p>
<ul>
    <li>Na predračunu jasno piše „Predračun" (ili „Ponuda – predračun"), da ga klijent ne knjiži kao račun.</li>
    <li>Navedi IBAN, poziv na broj i rok plaćanja — idealno i HUB-3 barkod.</li>
    <li>Kad uplata stigne, ona je za paušalista <strong>primitak</strong> na taj dan i upisuje se u KPR.</li>
</ul>

<h2>Račun</h2>
<p>
    Račun je <strong>poslovna isprava</strong> o obavljenoj isporuci ili usluzi i temelj za naplatu.
    Mora imati sve propisane elemente (naziv i OIB obrta, broj računa, datum, opis, iznos, napomenu o
    PDV-u…), za gotovinsku naplatu od građana i fiskalizaciju (JIR i ZKI), a od 2026./2027. prema
    tvrtkama sve češće ide kao <strong>eRačun</strong>.
</p>
<ul>
    <li>Račun se izdaje nakon obavljene usluge ili isporuke, ili po primljenom predujmu, ovisno o dogovoru.</li>
    <li>Ako je račun ispostavljen, a nije plaćen, on je i <strong>vjerodostojna isprava</strong> za ovrhu kod javnog bilježnika.</li>
    <li>Pogrešan račun se ne briše — izdaje se storno ili novi, ispravljeni račun.</li>
</ul>

