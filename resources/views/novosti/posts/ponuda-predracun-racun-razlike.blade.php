<h2>Tipičan tijek posla</h2>
<ol>
    <li>Pošalješ <strong>ponudu</strong>, klijent je prihvati.</li>
    <li>Za veće poslove pošalješ <strong>predračun</strong> za predujam (npr. 30–50 %).</li>
    <li>Kad posao završiš, izdaš <strong>račun</strong> za ukupni iznos, uz umanjenje za već plaćeni predujam.</li>
    <li>Naplatu upišeš u knjigu prometa — u plačko.app se ponuda jednim klikom pretvara u račun, a KPR se puni sam.</li>
</ol>

