<p>
    Račun često treba izdati „na terenu" — kod klijenta, na gradilištu, na sajmu. Zato se plačko.app može
    <strong>instalirati na mobitel kao aplikacija</strong>: dobiješ ikonu na početnom zaslonu, otvara se preko
    cijelog ekrana bez adresne trake preglednika i pamti prijavu. Ne treba App Store ni Google Play i ne
    zauzima gotovo nimalo prostora.
</p>

<h2>iPhone i iPad (Safari)</h2>
<ol>
    <li>Otvori <strong>placko.app</strong> u Safariju i prijavi se.</li>
    <li>Dodirni ikonu <strong>Dijeli</strong> (kvadrat sa strelicom prema gore) na dnu ekrana.</li>
    <li>Odaberi <strong>Dodaj na početni zaslon</strong> i potvrdi s <strong>Dodaj</strong>.</li>
</ol>

<h2>Android (Chrome)</h2>
<ol>
    <li>Otvori <strong>placko.app</strong> u Chromeu i prijavi se.</li>
    <li>Chrome će često sam ponuditi <strong>Instaliraj aplikaciju</strong>. Ako ne, dodirni izbornik (tri točkice) gore desno.</li>
    <li>Odaberi <strong>Instaliraj aplikaciju</strong> (ili <strong>Dodaj na početni zaslon</strong>) i potvrdi.</li>
</ol>

<h2>Računalo (Chrome ili Edge)</h2>
<p>
    I na računalu plačko.app može raditi u vlastitom prozoru: u adresnoj traci klikni ikonu
    <strong>Instaliraj</strong> (zaslon sa strelicom) ili u izborniku odaberi <strong>Instaliraj plačko.app</strong>.
</p>

<div class="callout">
    Instalirana aplikacija je ista ona koju koristiš u pregledniku — svi računi, ponude i klijenti su na
    istom mjestu i automatski usklađeni. Nadogradnje stižu same, ništa ne treba ažurirati ručno.
</div>

<h2>Što radi dobro na mobitelu</h2>
<ul>
    <li>izdavanje računa i ponuda, uz odabir klijenta i usluga iz popisa,</li>
    <li>slanje PDF-a računa ili ponude mailom izravno s mobitela,</li>
    <li>pregled koje su ponude prihvaćene,</li>
    <li>HUB-3 barkod na računu — klijent ga skenira mobilnim bankarstvom i plati bez prepisivanja IBAN-a.</li>
</ul>
