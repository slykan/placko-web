<p>
    Najčešće pitanje koje dobivamo od obrtnika koji prelaze u plačko.app usred godine glasi:
    <strong>„Što s brojevima računa? U starom programu sam stao na 57."</strong> Računi unutar godine
    moraju ići redom, bez preskakanja i bez ponavljanja — pa ne možeš jednostavno krenuti ispočetka od 1.
</p>
<p>
    Zato plačko.app sad ima postavku <strong>Numeracija računa</strong>: upišeš od kojeg broja aplikacija
    treba nastaviti, i prvi račun koji izdaš u plačko.app dobit će točno taj broj.
</p>

<h2>Kako se podešava</h2>
<ol>
    <li>Otvori <strong>Postavke</strong> i spusti se do odjeljka <strong>Numeracija računa</strong>.</li>
    <li>U polje <strong>Početni broj računa za 2026.</strong> upiši broj koji slijedi nakon zadnjeg računa iz starog programa.
        Ako je zadnji račun bio <code>57-1-2026</code>, upisuješ <code>58</code>.</li>
    <li>Ispod polja odmah vidiš kako će glasiti <strong>sljedeći račun</strong> — npr. <code>58-1-2026</code>. Spremi postavke.</li>
</ol>

<div class="callout">
    Postavka vrijedi samo za godinu za koju je upisana. Od 1. siječnja numeracija ponovno kreće od 1,
    kako i treba — ne moraš se sjetiti ništa vratiti.
</div>

<h2>Što ako u plačko.app već imam račune?</h2>
<p>
    Aplikacija uvijek uzima <strong>veći</strong> od dva broja: tvoj početni broj ili zadnji račun u
    plačko.app + 1. Ako si već izdao račune 58, 59 i 60, a naknadno upišeš početni broj 58, sljedeći
    račun i dalje će biti 61 — nikad se neće dogoditi da dva računa dobiju isti broj.
</p>
<p>
    Ako želiš da numeracija normalno kreće od 1 (npr. tek si otvorio obrt), polje jednostavno ostavi prazno.
</p>

<h2>Zašto je to važno</h2>
<p>
    Broj računa na računu paušalista i obrtnika sastoji se od rednog broja, oznake poslovnog prostora i
    oznake naplatnog uređaja (u plačko.app: <code>redni broj-1-godina</code>). Redni broj mora ići
    slijedno unutar godine. Ako bi nakon prelaska krenuo ispočetka, imao bi dva računa s brojem 1 u istoj
    godini — što je problem i za knjigu prometa i kod eventualnog nadzora. Više o tome što sve mora
    pisati na računu pročitaj u vodiču
