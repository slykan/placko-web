<p>
    Paušalni obrt je najjednostavniji način da u Hrvatskoj počneš legalno raditi za sebe: porez je fiksan
    i ovisi samo o razredu primitaka, nema vođenja poslovnih knjiga kao kod obrta na dohodak, a cijela
    registracija danas se može obaviti online. Ovo je pregled koraka od ideje do prvog računa — s
    naglaskom na ono što se u praksi najčešće zaboravi.
</p>

<h2>Prije prijave: je li paušal za tebe?</h2>
<p>
    Paušalno oporezivanje ima smisla ako ti godišnji <strong>primici ne prelaze 60.000 €</strong>
    (to je ujedno i prag za ulazak u sustav PDV-a od 1. siječnja 2025.) i ako nemaš velikih troškova
    poslovanja — porez se plaća prema primicima, a troškovi se ne odbijaju. Ako očekuješ veće troškove
    (npr. skupu opremu, najam prostora, zaposlenike), razmisli o obrtu na dohodak ili d.o.o.-u i
    porazgovaraj s knjigovođom.
</p>
<p>
    Važno je i pitanje <strong>osiguranja</strong>: obrt može biti tvoja jedina djelatnost (tada plaćaš
    pune doprinose, u 2026. oko 291 € mjesečno) ili ga voditi uz stalni posao (tada se za obrt plaćaju
    samo doprinosi za mirovinsko osiguranje, u znatno manjem iznosu i godišnje, prema rješenju Porezne
    uprave nakon PO-SD obrasca). Obje varijante prijavljuju se drukčije, pa to odluči prije registracije.
</p>

<h2>Korak 1: registracija obrta (START ili e-Obrt)</h2>
<p>
    Obrt se otvara u <strong>obrtnom registru</strong>. Najbrže je online, kroz sustav
    <strong>START</strong> ili <strong>e-Obrt</strong> na gov.hr portalu, uz prijavu e-osobnom ili
    tokenom banke. Može se i osobno, u nadležnom uredu za obrt u svojoj županiji. Trebat će ti:
</p>
<ul>
    <li><strong>naziv obrta</strong> — mora sadržavati tvoje ime i prezime i oznaku „obrt" (npr. „Web dizajn Ana, obrt za računalno programiranje, vl. Ana Horvat"),</li>
    <li><strong>sjedište</strong> — adresa na kojoj je obrt registriran (može biti i stan, ako djelatnost to dopušta),</li>
    <li><strong>predmet poslovanja</strong> — djelatnosti koje ćeš obavljati; neke (vezane i povlaštene) traže dokaz stručne spreme ili majstorski ispit,</li>
    <li>datum početka obavljanja djelatnosti.</li>
</ul>
<p>
    U sustavu START možeš odmah označiti i <strong>prijavu na mirovinsko i zdravstveno osiguranje</strong>
    (HZMO) — to se radi ako je obrt tvoja jedina djelatnost. Ako ostaješ zaposlen kod poslodavca, tu
    prijavu ne označavaš. Nakon upisa dobit ćeš izvadak iz obrtnog registra (u zakonskom roku od najviše
    15 dana, a u praksi često i brže).
</p>

<h2>Korak 2: Porezna uprava</h2>
<p>
    Nakon upisa obrt treba prijaviti u <strong>registar poreznih obveznika</strong> u nadležnoj ispostavi
    Porezne uprave (obrazac RPO), u pravilu u roku od <strong>8 dana</strong> od početka obavljanja
    djelatnosti. Tom prilikom biraš <strong>paušalno oporezivanje</strong> — inače te Porezna vodi kao
    obrt na dohodak. Ako si registraciju radio kroz START, dio podataka prenosi se automatski, ali
    provjeri u ePoreznoj da je obrt evidentiran kao paušalni.
</p>
<p>
    U prvoj godini porezni razred se određuje prema primicima koje <em>očekuješ</em>, a od druge
    godine prema stvarnim primicima iz prethodne godine. Porez se plaća tromjesečno; u 2026. on ide od
    50,85 € (najniži razred) do 270 € po tromjesečju (najviši razred), uz eventualni prirez.
</p>

<h2>Korak 3: žiro račun, fiskalizacija i eRačun</h2>
<ul>
    <li><strong>Poslovni račun u banci</strong> — obrt mora imati poseban transakcijski račun za poslovanje. Banke često nude pakete za obrtnike s niskom mjesečnom naknadom.</li>
    <li><strong>Fiskalizacija</strong> — ako ćeš izdavati račune građanima, treba ti FINA-in certifikat za fiskalizaciju i program koji račune šalje Poreznoj upravi. Uz to se donosi interni akt o poslovnim prostorima i naplatnim uređajima.</li>
    <li><strong>eRačun</strong> — od 1. siječnja 2026. i paušalisti moraju moći <strong>zaprimati</strong> e-račune od drugih poduzetnika, a obveza <strong>izdavanja</strong> e-računa za paušaliste kreće 1. siječnja 2027.</li>
</ul>

<h2>Korak 4: knjiga prometa i prvi račun</h2>
<p>
    Paušalist ne vodi poslovne knjige, ali mora voditi <strong>knjigu prometa (KPR)</strong> — evidenciju
    naplaćenih računa. Svaki račun mora imati obvezne elemente: naziv i OIB obrta, broj računa, datum,
    opis usluge, iznos i napomenu da PDV nije obračunat. Detaljno: <a href="{{ route('novosti.show', 'sto-mora-pisati-na-racunu-pausalni-obrt') }}" style="color:var(--p);font-weight:700;">što mora pisati na računu paušalnog obrta</a>
    i <a href="{{ route('novosti.show', 'knjiga-prometa-kpr-pausalni-obrt') }}" style="color:var(--p);font-weight:700;">kako voditi knjigu prometa</a>.
</p>

<h2>Kontrolna lista za prvih mjesec dana</h2>
<ol>
    <li>Upis u obrtni registar (START / e-Obrt) i, ako je obrt jedina djelatnost, prijava na HZMO.</li>
    <li>Prijava u registar poreznih obveznika i odabir paušalnog oporezivanja.</li>
    <li>Otvaranje poslovnog računa u banci.</li>
    <li>Ako radiš s građanima: certifikat za fiskalizaciju i interni akt.</li>
    <li>Program za račune i knjigu prometa (npr. plačko.app).</li>
    <li>Trajni nalog ili podsjetnik za mjesečne doprinose (do 15. u mjesecu za prethodni mjesec) i tromjesečni porez.</li>
</ol>

