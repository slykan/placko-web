</p>

<h2>Što kaže Zakon o zaštiti potrošača</h2>
<p>
    Izmjene Zakona objavljene su u Narodnim novinama 59/2026. Novi članak 7. stupa na snagu
    <strong>17. studenoga 2026.</strong> i glasi (izvadak):
</p>
<blockquote>
    (1) Trgovac mora jasno, vidljivo i čitljivo istaknuti iznos: – maloprodajne cijene – cijene za
    jedinicu mjere proizvoda koju pruža i – <strong>bazne cijene</strong>.<br>
    (8) Pri oglašavanju ističu se cijene iz stavka 1. ovoga članka […]<br>
    (9) Trgovac je dužan objaviti važeće cjenike proizvoda na svojim mrežnim stranicama.<br>
    (11) Ministar nadležan za područje zaštite potrošača pravilnikom propisuje za koji će se dan u
    prethodnom razdoblju, za koje proizvode i na koji način isticati bazna cijena […]
</blockquote>
<p>
    Zakon baznu cijenu definira kao <em>„maloprodajnu cijenu koja je bila primjenjiva na točno određen
    dan u prethodnom razdoblju”</em>. Koji je to dan i kako se ističe, propisat će pravilnik (vidi niže).
</p>

<h2>Što to znači u praksi</h2>
<ul>
    <li>Uz svaku cijenu proizvoda ili usluge mora stajati i <strong>bazna cijena</strong> — na prodajnom mjestu, u cjeniku na zidu, na web stranici i u web trgovini.</li>
    <li>Isto vrijedi i za <strong>oglase</strong> s cijenom (letci, plakati, oglasi na mreži).</li>
    <li>Ako cijenu od referentnog dana nisi mijenjao, bazna cijena jednaka je trenutnoj — ali obje moraju biti istaknute.</li>
    <li>Tko ima web stranicu, mora na njoj objaviti <strong>važeći cjenik</strong>; prema odluci Vlade o objavi cjenika to je strojno čitljiva datoteka (CSV ili XML) koja sadrži i baznu cijenu.</li>
    <li>Za proizvod ili uslugu uvedenu nakon referentnog dana, prema nacrtu pravilnika, bazna je cijena ona s dana uvođenja u ponudu.</li>
</ul>

<div class="warn">
    <strong>Kazne:</strong> prema izmijenjenom Zakonu o zaštiti potrošača trgovac – pravna osoba koji ne
    istakne baznu cijenu jasno, vidljivo i čitljivo, ne istakne je u oglasu ili ne objavi važeće cjenike
    na svojim mrežnim stranicama kažnjava se s <strong>1.500 do 50.000 eura</strong>. Kazne za obrtnike i
    odgovorne osobe propisane su u istom zakonu, u nižim iznosima. Ako nisi siguran odnosi li se obveza
    na tvoju djelatnost, provjeri s knjigovođom ili obrtničkom komorom.
</div>

<h2>Pravilnici: još su nacrti</h2>
<p>
    Ministarstvo gospodarstva u listopadu 2026. otvorilo je javno savjetovanje o dva pravilnika koja
    razrađuju Zakon. Dok ne budu objavljeni u Narodnim novinama, <strong>detalji se još mogu promijeniti</strong>.
    Prema nacrtima:
</p>
<ul>
    <li>referentni dan je <strong>2. svibnja 2025.</strong> za hranu, piće, kozmetiku, sredstva za čišćenje, toaletne potrepštine i proizvode za kućanstvo, a <strong>10. rujna 2026.</strong> za sve ostale proizvode i sve usluge;</li>
    <li>ako je na referentni dan bila akcija, bazna cijena je redovna (neakcijska) cijena;</li>
    <li>ne odnosi se na personalizirane cijene ponuđene samo jednom potrošaču ni na dinamički određene cijene usluga koje se ne mogu vezati uz referentni dan;</li>
    <li>oba pravilnika trebala bi se primjenjivati od <strong>17. studenoga 2026.</strong></li>
</ul>

