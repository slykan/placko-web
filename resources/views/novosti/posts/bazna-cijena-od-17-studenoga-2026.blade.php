<p>
    Obveza isticanja <strong>sidrene cijene</strong> nije krenula 1. listopada. Vlada ju je
    <strong>odgodila na 17. studenoga 2026.</strong>, a od istog dana na snagu stupa i izmijenjeni
    <strong>Zakon o zaštiti potrošača</strong>, koji tu istu cijenu trajno uvodi u zakon pod novim
    imenom: <strong>bazna cijena</strong>. Ispod je sažetak i popis svih službenih dokumenata, s
    poveznicama na Narodne novine.
</p>

