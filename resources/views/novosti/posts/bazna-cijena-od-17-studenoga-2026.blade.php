<h2>Kontrolna lista do 17. studenoga</h2>
<ol>
    <li>Imaš zapisane cijene svih proizvoda i usluga na referentni dan (10. 9. 2026. ili 2. 5. 2025.)? To su tvoje bazne cijene.</li>
    <li>Uz svaku cijenu u poslovnom prostoru dodaj i baznu cijenu.</li>
    <li>Isto napravi na web stranici, u web trgovini, na društvenim mrežama i u oglasima gdje navodiš cijene.</li>
    <li>Ako imaš web stranicu, objavi važeći cjenik (CSV ili XML) s baznom cijenom i ažuriraj ga nakon svake promjene.</li>
    <li>Prije 17. studenoga provjeri jesu li pravilnici objavljeni u Narodnim novinama i je li se što promijenilo u odnosu na nacrte.</li>
</ol>
