<p>
    Svaki obrtnik prije ili kasnije dobije klijenta koji ne plati na vrijeme. Većina dugova riješi se
    jednim podsjetnikom, ali korisno je znati cijeli put — od ljubazne poruke do ovrhe — i rokove koji
    ti ne smiju promaknuti. Ovo je praktičan pregled za male poduzetnike.
</p>

<h2>1. Spriječi problem na računu</h2>
<ul>
    <li>Na računu jasno navedi <strong>rok plaćanja</strong> (datum dospijeća), IBAN i poziv na broj — i HUB-3 barkod, da se plaća u dvije sekunde.</li>
    <li>Za veće poslove traži <strong>predujam</strong> (predračun) prije početka rada.</li>
    <li>Ako račun ide <strong>građaninu</strong> (fizičkoj osobi koja nije poduzetnik), na računu mora biti <strong>upozorenje</strong> da vjerovnik može predložiti ovrhu na temelju vjerodostojne isprave ako dug ne bude plaćen o dospijeću. Bez tog upozorenja račun prema građaninu nije prikladan za ovrhu kod javnog bilježnika.</li>
</ul>

<h2>2. Podsjetnik i opomena</h2>
<p>
    Prvi korak je kratak, ljubazan <strong>podsjetnik</strong> nekoliko dana nakon dospijeća — često je
    račun jednostavno zaboravljen. Ako ni to ne pomogne, pošalji <strong>opomenu</strong>: pisani zahtjev
    s brojem i datumom računa, dugovanim iznosom, novim rokom (npr. 8 dana) i najavom da ćeš nakon toga
    pokrenuti naplatu putem ovrhe. Opomenu pošalji e-mailom i, za veće iznose, preporučenom poštom.
</p>
<p>
    Od dana dospijeća dužnik duguje i <strong>zatezne kamate</strong>. Stopa se mijenja svakih šest mjeseci:
    računa se kao referentna stopa uvećana za 8 postotnih poena između poduzetnika, odnosno za 5 postotnih
    poena u ostalim odnosima. Aktualnu stopu provjeri prije obračuna.
</p>

<h2>3. Ovrha na temelju vjerodostojne isprave</h2>
<p>
    Za neplaćeni račun ne trebaš sudsku presudu. Račun je <strong>vjerodostojna isprava</strong> (kao i
    izvadak iz poslovnih knjiga ili obračun kamata), pa ovrhu možeš predložiti kod <strong>javnog
    bilježnika</strong>:
</p>
<ol>
    <li>Javni bilježnik na temelju računa donosi <strong>rješenje o ovrsi</strong> i dostavlja ga dužniku.</li>
    <li>Dužnik ima <strong>8 dana</strong> da plati dug s troškovima ili podnese <strong>prigovor</strong>.</li>
    <li>Ako ne podnese prigovor, rješenje postaje pravomoćno i ovršno, a ovrhu na računima dužnika provodi <strong>FINA</strong>.</li>
    <li>Ako dužnik podnese prigovor, predmet ide na sud, koji odlučuje o tvom zahtjevu kao u parnici.</li>
</ol>
<p>
    Troškove ovrhe (javnobilježničku nagradu, pristojbe) predujmljuješ ti, a u rješenju se nalaže dužniku
    da ih nadoknadi. Za male iznose usporedi troškove s iznosom duga.
</p>

<h2>4. Pazi na zastaru</h2>
<p>
    Potraživanja ne vrijede zauvijek. Međusobna potraživanja <strong>između poduzetnika</strong> iz
    ugovora o prometu robe i usluga zastarijevaju za <strong>tri godine</strong> (čl. 228. Zakona o
    obveznim odnosima), a zastara teče posebno za svaku isporuku ili uslugu, od dana dospijeća. Za
    ostala potraživanja opći rok je pet godina, a za neke vrste potraživanja prema građanima rokovi
    mogu biti kraći. Ne čekaj zadnji mjesec — ovrhu pokreni dok je dug svjež i dužnik još posluje.
</p>

<h2>5. Porezno: što s nenaplaćenim računom?</h2>
<p>
    Za paušalista je jedna stvar jednostavnija nego za druge: u knjigu prometa i PO-SD ulazi samo
    <strong>naplaćeni</strong> iznos. Dok račun nije plaćen, ne plaćaš ni porez na njega. Kad dug
    naplatiš (dobrovoljno ili ovrhom), naplatu upisuješ na dan kad je novac sjeo na račun.
</p>

