<p>
    Jednom godišnje svaki paušalist predaje <strong>PO-SD obrazac</strong> — izvješće o paušalnom
    dohotku. Iz njega Porezna uprava utvrđuje tvoj porezni razred za iduću godinu i provjerava jesi li
    tijekom godine platio dovoljno poreza. Ispunjavanje nije komplicirano ako ti je knjiga prometa
    uredna. Evo kako.
</p>

<h2>Rok i način predaje</h2>
<div class="callout">
    PO-SD se predaje do <strong>15. siječnja</strong> tekuće godine za prethodnu godinu — za primitke iz
    2026. rok je <strong>15. siječnja 2027.</strong> Predaje se elektronički, putem <strong>ePorezne</strong>.
</div>
<p>
    Paušalisti koji zajednički obavljaju djelatnost (zajednički obrt) u istom roku predaju obrazac
    <strong>PO-SD-Z</strong>. Ako je obrt otvoren ili zatvoren tijekom godine, obrazac se predaje za
    razdoblje u kojem je djelatnost obavljana.
</p>

<h2>Što ti treba</h2>
<ul>
    <li><strong>Knjiga prometa (KPR)</strong> za cijelu godinu — iz nje uzimaš ukupne primitke.</li>
    <li>Podaci o <strong>uplaćenom porezu</strong> tijekom godine (tromjesečne uplate) — vidljivi u ePoreznoj, na kartici poreznog obveznika.</li>
    <li>Pristup <strong>ePoreznoj</strong> (e-osobna, token banke ili drugi NIAS ključ).</li>
</ul>

<h2>Kako se ispunjava, korak po korak</h2>
<ol>
    <li><strong>Primici</strong> — upiši ukupne <em>naplaćene</em> primitke iz KPR-a, odvojeno gotovinske i bezgotovinske. Račun izdan u prosincu, a naplaćen u siječnju, ne ulazi u ovu godinu.</li>
    <li><strong>Razred</strong> — prema ukupnim primicima određuje se porezni razred (u 2026. sedam razreda, od primitaka do 11.300 € u prvom do 60.000 € u sedmom). U ePoreznoj se razred i iznos godišnjeg poreza izračunavaju sami.</li>
    <li><strong>Uplaćeni porez</strong> — upisuju se tromjesečne uplate poreza (i prireza, gdje se plaća) tijekom godine.</li>
    <li><strong>Razlika</strong> — ako je godišnji porez veći od uplaćenog, razliku treba <strong>uplatiti s danom podnošenja</strong> obrasca. Ako si platio više, preplata se uračunava u buduće obveze ili vraća.</li>
    <li><strong>Doprinosi</strong> — ako ti je obrt jedina djelatnost, doprinose plaćaš mjesečno i u PO-SD ih ne obračunavaš ponovno; ako radiš uz stalni posao, na temelju PO-SD-a dobit ćeš rješenje o godišnjim doprinosima za mirovinsko osiguranje.</li>
</ol>

<h2>Što se mijenja nakon predaje</h2>
<p>
    Ako su ti primici prešli granicu razreda, od siječnja plaćaš tromjesečni porez prema <strong>novom
    razredu</strong> — Porezna uprava izdaje rješenje, a novi iznosi vidljivi su u ePoreznoj. Ako su
    ti primici premašili <strong>60.000 €</strong>, više ne možeš biti paušalist: obrt prelazi na
    oporezivanje dohotka, a prelaskom praga ulaziš i u sustav PDV-a (vidi
    <a href="{{ route('novosti.show', 'pausalni-obrt-i-pdv-prag-60000') }}" style="color:var(--p);font-weight:700;">paušalni obrt i PDV</a>).
</p>

<h2>Najčešće pogreške</h2>
<ul>
    <li>Upis izdanih umjesto naplaćenih računa.</li>
    <li>Zaboravljeni predujmovi ili djelomične uplate.</li>
    <li>Predaja nakon roka — za zakašnjelo podnošenje propisane su novčane kazne, a i bez kazne kasniš s utvrđivanjem razreda.</li>
    <li>Neplaćena razlika poreza na dan predaje, zbog čega se obračunavaju zatezne kamate.</li>
</ul>

