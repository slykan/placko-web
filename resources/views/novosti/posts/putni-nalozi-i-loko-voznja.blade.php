<p>
    Svako službeno putovanje treba putni nalog, a svaka vožnja privatnim autom po gradu evidenciju loko vožnje.
    Inače dnevnice i kilometri nisu neoporezivi. U plačko.app sad postoje <strong>putni nalozi</strong>
    (tuzemni i inozemni) i <strong>loko vožnja</strong>. Obračun se radi sam, a knjigovođa dobije uredan PDF.
    Dostupno je u paketima <strong>Pro</strong> i <strong>Business</strong>, uz radne naloge.
</p>

<h2>1. Upiši vozilo kod zaposlenika</h2>
<p>
    U <strong>Zaposlenicima</strong> svakome upiši <strong>registarsku oznaku</strong> i marku vozila koje vozi.
    One se onda same predlažu na putnom nalogu i u loko vožnji. Registarska oznaka je obavezan podatak
    kad se putuje automobilom, pa je aplikacija neće pustiti da je preskočiš.
</p>

<h2>2. Otvori putni nalog</h2>
<p>
    U izborniku <strong>Putni nalozi</strong> klikni <strong>+ Novi putni nalog</strong> i upiši:
</p>
<ul>
    <li><strong>putnika</strong>: zaposlenika iz popisa ili, za vlasnika i direktora, samo ime i funkciju,</li>
    <li><strong>tuzemno ili inozemstvo</strong> te odredište, a za inozemstvo i <strong>državu</strong>,</li>
    <li><strong>svrhu putovanja</strong> i tko nalog izdaje,</li>
    <li><strong>prijevozno sredstvo</strong> s registarskom oznakom i stanjem brojila na polasku i povratku,</li>
    <li><strong>polazak i povratak</strong>, a kod inozemnog puta i vrijeme prelaska granice,</li>
    <li>po potrebi <strong>predujam</strong> i broj osiguranih obroka.</li>
</ul>
<div class="callout">
    Ideš na teren zbog radnog naloga? Klikni <strong>Iz radnog naloga</strong>. Putnik (nositelj posla),
    odredište i svrha prepišu se sami.
</div>

<h2>3. Obračun se radi sam</h2>
<p>
    Čim spremiš nalog, plačko.app izračuna dnevnice, kilometre i ostale troškove po neoporezivim iznosima:
</p>
<ul>
    <li><strong>dnevnica u Hrvatskoj</strong>: 30,00 € za put dulji od 12 sati, 15,00 € za 8–12 sati, a do 8 sati dnevnice nema,</li>
    <li><strong>privatni automobil</strong>: 0,50 € po prijeđenom kilometru (službeni auto nema naknadu po km, gorivo se upisuje kao trošak),</li>
    <li><strong>inozemne dnevnice</strong>: po tablici za 106 država iz Odluke Vlade RH (NN 16/2024), npr. Njemačka i Austrija 90 €,
        Slovenija i Italija 80 €, BiH i Srbija 50 €; za put od 8 do 12 sati pola iznosa,</li>
    <li>na inozemnom putu vrijeme od kuće do granice i natrag obračunava se kao tuzemno, a vrijeme vani po državi,</li>
    <li>za države s dnevnicom u dolarima uzima se <strong>srednji tečaj HNB-a</strong> na dan povratka, ili ga upišeš ručno,</li>
    <li>osigurani obrok umanjuje dnevnicu za 30 % (dva obroka za 60 %),</li>
    <li>predujam se oduzima, pa vidiš točan iznos <strong>za isplatu</strong> ili povrat.</li>
</ul>
<p>
    Troškove poput karte, cestarine, parkinga i smještaja dodaješ sa <strong>slikom ili PDF-om računa</strong>.
    Slike se čuvaju na privatnom disku, nisu javno dostupne.
</p>

<h2>4. Zaposlenik upisuje s mobitela</h2>
<p>
    Na svom osobnom linku <strong>Moji nalozi</strong> zaposlenik sad vidi i svoje putne naloge. Upiše
    stvarni polazak i povratak, brojilo kilometara i izvješće s puta, a račun za parking ili cestarinu
    <strong>slika mobitelom</strong> i odmah priloži. Odmah vidi i koliko mu pripada.
</p>

<h2>5. PDF za knjigovođu</h2>
<p>
    Gumb <strong>PDF</strong> daje putni nalog na jednoj stranici: nalog, obračun putnih troškova, izvješće s puta
    i mjesta za potpise (podnositelj, likvidator, odobrio). Kad je sve provjereno, nalog označiš
    kao <em>Obračunat</em>, a nakon isplate kao <em>Isplaćen</em>.
</p>

<h2>6. Loko vožnja iz radnih naloga</h2>
<p>
    Loko vožnja je vožnja privatnim autom u službene svrhe unutar mjesta rada, npr. od radionice do klijenta.
    U izborniku <strong>Loko vožnja</strong> klikni <strong>Uvezi iz radnih naloga</strong>, odaberi zaposlenika i mjesec,
    pa svaki njegov dolazak na radni nalog postaje redak s datumom, vremenom, relacijom
    (polazište – klijent – polazište), svrhom i registracijom. Ti samo upišeš prijeđene kilometre.
    Redovi bez kilometara označeni su crveno.
</p>
<p>
    <strong>Mjesečna evidencija (PDF)</strong> zbraja kilometre i iznos po 0,50 €/km, s mjestima za potpis.
    To je dokaz koji knjigovođa treba da bi naknada ostala neoporeziva.
</p>

<h2>Na što paziti</h2>
<ul>
    <li>Paušalist sam sebi ne isplaćuje neoporezive dnevnice ni kilometre. Putni nalozi koriste se za
        <strong>zaposlenike</strong>, a vlasnicima i direktorima obrta na dohodak, j.d.o.o. i d.o.o.</li>
    <li>Isplaćene dnevnice i naknade prijavljuju se na obrascu JOPPD. To radi knjigovođa ili program za plaće,
        a plačko.app daje podatke i PDF.</li>
    <li>Iznosi su provjereni u Narodnim novinama 10.11.2026. Kad se propis promijeni, ažuriramo ih za sve korisnike.</li>
</ul>
